/**
 * 物种前缀归一化（原版 @Global.ecode L91「精英前缀替换」+ 使魔大战.txt L22 配置：
 *   精英前缀替换=精英 神兽 深蓝 巨型
 * 用途：把「精英史莱姆」「神兽白虎」这类带物种前缀的名字还原为基名，
 *   保证同名物种共用同一份数据（图片、对话、全局熟练度计数）。
 *
 * 对应原版两处调用：
 *   1. 数据显示.ecode L1640 显示熟练度等级(..., 是否去掉物种前缀=真)
 *      → 熟练度按基名合并：精英史莱姆 与 史莱姆 共用「史莱姆熟练度」。
 *      该分支同时剔除「分身」（宠物分身与本体共用熟练度）。
 *   2. 数据显示.ecode L128-136 取对话 的对象类型归一化。
 *
 * 单一实现约束：规则只在此处维护，调用方不得内联重复实现。
 * 注意：原版对 NPC 类还有 npc1g→神之工匠、小樱2→小樱 两项**特例**，
 * 那是「对象类型归一化」而非「物种前缀替换」，由调用方在调用本函数前自行处理。
 */

/** 原版 使魔大战.txt L22：精英前缀替换=精英 神兽 深蓝 巨型 */
export const SPECIES_PREFIXES: readonly string[] = ['精英', '神兽', '深蓝', '巨型'];

/**
 * 去掉物种前缀：先剔除「分身」（原版 显示熟练度等级 的物种前缀分支），
 * 再按 精英/神兽/深蓝/巨型 顺序整体替换为空。
 */
export function stripSpeciesPrefix(name: string): string {
  let out = String(name ?? '').split('分身').join('');
  for (const prefix of SPECIES_PREFIXES) {
    out = out.split(prefix).join('');
  }
  return out;
}
